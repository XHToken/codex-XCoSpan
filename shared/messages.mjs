export function responseLanguage(args = {}, fallback = 'en') {
  if (typeof args.response_language === 'string' && /^[A-Za-z]{2,8}(?:-[A-Za-z0-9]{1,8})*$/.test(args.response_language)) return args.response_language;
  // Compatibility only; the main session determines language from user intent.
  if (typeof args.prompt === 'string' && /[\u3400-\u9fff]/u.test(args.prompt)) return 'zh-CN';
  return fallback;
}

export function translate(source, language, translations = {}) {
  if (/^zh(?:-|$)/i.test(language)) return source;
  if (!/^en(?:-|$)/i.test(language) && Object.hasOwn(translations, source)) return translations[source];
  return englishMessages[source] || source;
}
